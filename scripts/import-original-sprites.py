"""Rebuild the original character data from the credited source sheets.

Run with Python and Pillow. This is an offline development tool, not a game dependency.
Only black source pixels are imported. No scaling or redrawing is performed.
"""
import json
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'reference' / 'original-sprites'


def extract(image, box):
    x, y, width, height = box
    return [''.join('1' if max(image.getpixel((x + dx, y + dy))[:3]) < 100
                   and image.getpixel((x + dx, y + dy))[3] else '0'
                   for dx in range(width)) for dy in range(height)]


def main():
    manifest = json.loads((SOURCE / 'frames.json').read_text())
    data = {}
    for identity, entry in manifest.items():
        image = Image.open(SOURCE / entry['file']).convert('RGBA')
        frames = [extract(image, box) for box in entry['boxes']]
        data[identity] = {pose: frames[index] for pose, index in entry['poses'].items()}
    output = '// Source pixels from DemiumAjare. See reference/original-sprites/README.md and NOTICE.md.\n'
    output += '// Generated by scripts/import-original-sprites.py. Edit the frame manifest to change poses.\n'
    output += 'const rows = ' + json.dumps(data, indent=2) + ';\n'
    output += '''export const originalSprites = Object.freeze(Object.fromEntries(
  Object.entries(rows).map(([identity, poses]) => [identity, Object.freeze(Object.fromEntries(
    Object.entries(poses).map(([pose, drawing]) => [pose,
      Object.freeze(drawing.map(row => Object.freeze([...row].map(Number))))
    ])
  ))])
));
'''
    (ROOT / 'pets' / 'original-sprites.js').write_text(output)


if __name__ == '__main__':
    main()
